/* SA1 - Banco da indústria de embalagens */
DROP DATABASE IF EXISTS embalagens;
CREATE DATABASE embalagens;
USE embalagens;
create table IF NOT EXISTS PRODUTO (
	ID_PRODUTO INT AUTO_INCREMENT PRIMARY KEY,
	Nome VARCHAR(100),
	preco_tabela INT NOT NULL
);

CREATE TABLE IF NOT EXISTS CLIENTE (
	ID_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
	RAZAO_SOCIAL INT NOT NULL,
	CIDADE VARCHAR(50) NOT NULL,
	CNPJ VARCHAR(14) UNIQUE NOT NULL
);

CREATE TABLE IF NOT EXISTS RESINA (
	ID_RESINA INT AUTO_INCREMENT PRIMARY KEY,
	NOME VARCHAR(50),
    ID_PRODUTO INT NOT NULL,
    FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO)
);

CREATE TABLE IF NOT EXISTS UNIDADE (
	ID_UNIDADE INT AUTO_INCREMENT PRIMARY KEY,
	Nome VARCHAR(100) NOT NULL,
	cidade VARCHAR(100) NOT NULL,
	telefone VARCHAR(14),
     ID_RESINA INT NOT NULL,
    FOREIGN KEY (ID_RESINA) REFERENCES RESINA(ID_RESINA)
  
);


 CREATE TABLE IF NOT EXISTS EXPEDIÇÃO (
	 ID_EXPEDICÃO  INT AUTO_INCREMENT PRIMARY KEY,
	 Número INT NOT NULL,
	 DATA DATE,
     ID_PRODUTO INT NOT NULL,
     FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO)
     
 );
 
 CREATE TABLE IF NOT EXISTS ORDEM_PRODUÇÃO (
	 ID_ORDEM_PRODUÇÃO INT AUTO_INCREMENT PRIMARY KEY,
	 Número INT NOT NULL,
	 data DATE NOT NULL,
     ID_UNIDADE INT NOT NULL,
     FOREIGN KEY (ID_UNIDADE) REFERENCES UNIDADE(ID_UNIDADE),
     ID_PRODUTO INT NOT NULL,
     FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO(ID_PRODUTO)
 );

